export const BS_MONTH_NAMES = [
  "Baishakh", "Jestha", "Ashadh", "Shrawan", "Bhadra", "Ashwin",
  "Kartik", "Mangsir", "Poush", "Magh", "Falgun", "Chaitra",
];

// Reference: BS 2000-01-01 == AD 1943-04-14.
const BS_EPOCH_YEAR = 2000;
const AD_EPOCH = Date.UTC(1943, 3, 14); // months are 0-indexed
const MS_PER_DAY = 86400000;

export const BS_MIN_YEAR = BS_EPOCH_YEAR;
export const BS_MAX_YEAR = 2090;

export interface BsDate {
  year: number;
  month: number; // 1-12
  day: number; // 1-32
}

/** Days from the BS epoch to BS-year start (year 1st Baishakh). */
function daysToBsYearStart(year: number): number {
  let days = 0;
  for (let y = BS_EPOCH_YEAR; y < year; y++) {
    const months = BS_MONTHS[y];
    for (let m = 0; m < 12; m++) days += months[m];
  }
  return days;
}

/** Convert a Gregorian date to Bikram Sambat. Returns null if out of table range. */
export function adToBs(date: Date): BsDate | null {
  const utc = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  let offset = Math.round((utc - AD_EPOCH) / MS_PER_DAY);
  if (offset < 0) return null;

  let year = BS_EPOCH_YEAR;
  while (year <= BS_MAX_YEAR) {
    const months = BS_MONTHS[year];
    const yearDays = months.reduce((s, d) => s + d, 0);
    if (offset < yearDays) {
      for (let m = 0; m < 12; m++) {
        if (offset < months[m]) return { year, month: m + 1, day: offset + 1 };
        offset -= months[m];
      }
    }
    offset -= yearDays;
    year++;
  }
  return null; // beyond supported range
}

/** Convert a Bikram Sambat date to a Gregorian Date (at local midnight). */
export function bsToAd(bs: BsDate): Date | null {
  if (bs.year < BS_MIN_YEAR || bs.year > BS_MAX_YEAR) return null;
  const months = BS_MONTHS[bs.year];
  let days = daysToBsYearStart(bs.year);
  for (let m = 0; m < bs.month - 1; m++) days += months[m];
  days += bs.day - 1;
  const utc = AD_EPOCH + days * MS_PER_DAY;
  const d = new Date(utc);
  return new Date(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate());
}

/** Format a Gregorian date as a BS date string, e.g. "20 Ashadh 2083". Null if out of range. */
export function formatBsDate(date: Date): string | null {
  const bs = adToBs(date);
  if (!bs) return null;
  return `${bs.day} ${BS_MONTH_NAMES[bs.month - 1]} ${bs.year}`;
}

/** Number of days in a given BS month (1–12). Returns 0 if the year is unsupported. */
export function bsMonthLength(year: number, month: number): number {
  return BS_MONTHS[year]?.[month - 1] ?? 0;
}

/** Today's date in BS (falls back to the epoch if out of range). */
export function todayBs(): BsDate {
  return adToBs(new Date()) ?? { year: BS_MIN_YEAR, month: 1, day: 1 };
}

/** All BS years covered by the conversion table, ascending. */
export function bsYears(): number[] {
  const years: number[] = [];
  for (let y = BS_MIN_YEAR; y <= BS_MAX_YEAR; y++) years.push(y);
  return years;
}
